/** The article with its sign-off applied, or unchanged when none names it. A reviewer set in the file itself wins. */
export function applySignoffs(a: ConditionArticle): ConditionArticle {
  if (a.reviewer) return a;
  for (const s of SIGNOFFS) if (s.slugs.includes(a.slug)) return { ...a, reviewer: s.reviewer, reviewedOn: s.on };
  return a;
}
